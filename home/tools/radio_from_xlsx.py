#!/usr/bin/env python3
"""Turn the UV-5R guide workbook into src/radiodata.ts for the Radio app.

  python3 tools/radio_from_xlsx.py tools/UV-5R_Fargo_Guide.xlsx

Needs openpyxl (pip install openpyxl). Re-run after editing the workbook, then build + update.sh.
"""
import json
import os
import sys

import openpyxl

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "UV-5R_Fargo_Guide.xlsx")
out = os.path.join(os.path.dirname(__file__), "..", "src", "radiodata.ts")
wb = openpyxl.load_workbook(src, data_only=True)


def s(v):
    if v is None:
        return ""
    if isinstance(v, float):
        return ("%.4f" % v).rstrip("0").rstrip(".")
    return str(v).strip()


def rows(name):
    ws = wb[name]
    data = [[s(c) for c in r] for r in ws.iter_rows(values_only=True)]
    return [r for r in data if any(r)]


def freq(v):
    try:
        return "%.3f" % float(v)
    except ValueError:
        return v


def tx_class(text):
    t = text.lower()
    if "ham license" in t:
        return "ham"
    return "rx"


# ---- Fargo channels
fc = rows("Fargo Channels")
hdr, body = fc[0], fc[1:]
channels, chan_notes = [], []
for r in body:
    if r[0].isdigit():
        channels.append({
            "ch": int(r[0]), "name": r[1], "freq": freq(r[2]), "offset": r[3], "tone": r[4], "width": r[5],
            "type": r[6], "where": r[7], "tx": r[8], "notes": r[9], "source": r[10], "cls": tx_class(r[8]),
        })
    elif r[0]:
        chan_notes.append(r[0])

# ---- FRS & GMRS
fg = rows("FRS & GMRS")
frs, frs_notes = [], []
for r in fg[1:]:
    if r[0].isdigit():
        frs.append({"ch": int(r[0]), "freq": freq(r[1]), "group": r[2], "frsPower": r[3], "frsWidth": r[4],
                    "gmrsPower": r[5], "gmrsWidth": r[6], "repeaterIn": r[7], "uv5r": r[8]})
    elif r[0]:
        frs_notes.append(r[0])

# ---- Menu settings
ms = rows("Menu Settings")
menu, menu_notes = [], []
for r in ms[1:]:
    if r[0].isdigit():
        menu.append({"n": int(r[0]), "screen": r[1], "what": r[2], "set": r[3], "for": r[4]})
    elif r[0]:
        menu_notes.append(r[0])

# ---- Info: Start Here (sections by heading) + Digital
sh = [r[0] for r in rows("Start Here")]
title = sh[0]
headings = {"What is in this workbook", "How to use the menu", "The rules, in plain English (US)", "Color key"}
info, cur = [], None
for line in sh[1:]:
    if line in headings or line.startswith("Sources ("):
        cur = {"title": line, "lines": []}
        info.append(cur)
    elif cur:
        cur["lines"].append(line)
dg = rows("Digital (can't hear)")
digital = [{"freq": r[0], "who": r[1], "mode": r[2], "notes": r[3]} for r in dg[1:] if r[0]]

data = {"title": title, "channels": channels, "channelNotes": chan_notes, "frs": frs, "frsNotes": frs_notes,
        "menu": menu, "menuNotes": menu_notes, "info": info, "digital": digital}
with open(out, "w") as f:
    f.write("// Generated by tools/radio_from_xlsx.py from %s. Edit the workbook, not this file.\n" % os.path.basename(src))
    f.write("/* eslint-disable */\nexport const RADIO = ")
    f.write(json.dumps(data, indent=1, ensure_ascii=False))
    f.write(" as const\n")
print("wrote", out, "-", len(channels), "channels,", len(frs), "FRS/GMRS,", len(menu), "menu items,", len(info), "info sections,", len(digital), "digital")
